export const login = async (req, res) => {
  try {
    const { username, password } = req.body;

    const user = await prisma.user.findFirst({
      where: { username },
      include: { role: true },
    });

    if (!user) {
      return res.status(401).json({ message: "Invalid username or password" });
    }

    const passwordMatches = await bcrypt.compare(password, user.password);
    if (!passwordMatches) {
      return res.status(401).json({ message: "Invalid username or password" });
    }

    const accessToken = crypto.randomBytes(32).toString("hex");
    await prisma.token.create({
      data: { token: accessToken, userId: user.id },
    });

    const loginTime = new Date();
    const log = await prisma.log.create({
      data: {
        userId: user.id,
        firstName: user.firstName,
        lastName: user.lastName,
        roleId: user.roleId,
        loginTime,
      },
    });

    return res.status(200).json({
      message: "Login Successful",
      accessToken,
      isAdmin: !!user.role?.isAdmin,
      isBuyer: !!user.role?.isBuyer,
      isProcurementManager: !!user.role?.isProcurementManager,
      name: `${user.firstName} ${user.lastName}`,
      email: user.email,
      userName: user.username,
      canViewDashboard: user.canViewDashboard,
      allowedModules: user.allowedModules,
      userId: user.id,
      roleId: user.roleId,
      firstName: user.firstName,
      lastName: user.lastName,
      loginTime,
      logId: log.id,
    });
  } catch (error) {
    console.error("Error in login:", error);
    return res.status(500).json({ message: "Failed to log in" });
  }
};

export const logout = async (req, res) => {
  try {
    const accessToken = req.headers["authorization"]?.substring(7);
    if (accessToken) {
      await prisma.token.deleteMany({ where: { token: accessToken } });
    }
    return res.status(200).json({ message: "Logged out" });
  } catch (error) {
    console.error("Error in logout:", error);
    return res.status(500).json({ message: "Failed to log out" });
  }
};

export const deleteUser = async (req, res) => {
  try {
    const { id } = req.params;

    if (!id) {
      return res.status(400).json({ message: "User ID is required" });
    }

    // Check if user exists before deleting
    const existingUser = await prisma.user.findUnique({
      where: { id },
    });

    if (!existingUser) {
      return res.status(404).json({ message: "User not found" });
    }

    // Delete the user
    await prisma.user.delete({
      where: { id },
    });

    return res.status(200).json({ message: "User deleted successfully" });
  } catch (error) {
    console.error("Error in deleteUser:", error);
    return res.status(500).json({ message: "Failed to delete user" });
  }
};
